def set_language(language: str) -> None:
    """Set the process-wide UI language (``en`` or ``it``)."""
    global _language
    language = str(language).lower().strip()
    if language not in _SUPPORTED:
        raise ValueError(f"Unsupported language: {language!r}")
    _language = language
    os.environ["SAR_LANGUAGE"] = language


def get_language() -> str:
    return _language


def tr(key: str, **kwargs: Any) -> str:
    """Return one translated string and apply ``str.format`` if requested."""
    table = _TRANSLATIONS.get(_language, _TRANSLATIONS["en"])
    text = table.get(key, _TRANSLATIONS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text


def is_italian() -> bool:
    return _language == "it"


def yes_no(value: bool) -> str:
    return tr("yes") if value else tr("no")

