def localize_analysis_text(value: Any) -> str:
    """Localise known analysis labels without changing stored result keys."""
    text = str(value)
    if _language == "it":
        return text
    if text.startswith("non lineare: "):
        suffix = text.split(": ", 1)[1]
        return "non-linear: " + _ANALYSIS_EN.get(suffix, suffix)
    return _ANALYSIS_EN.get(text, text)
